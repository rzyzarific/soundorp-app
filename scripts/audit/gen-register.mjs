// Regenerates docs/spec-verification.md from the catalog's `verification` records.
//
//   node scripts/audit/gen-register.mjs          # writes docs/spec-verification.md
//
// Inputs: src/data/devices.json (the records), scripts/audit/audit-groups.json (which devices each
// audit actually examined) and scripts/audit/register-handwritten.md (prose that is not derived from
// data). A test fails if the committed register is not what this script produces.
import fs from 'node:fs'
import { pathToFileURL } from 'node:url'

const ROOT = new URL('../../', import.meta.url)
const read = (p) => fs.readFileSync(new URL(p, ROOT), 'utf8').replace(/\r\n/g, '\n')

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ')
const code = (ids) => ids.map((i) => `\`${i}\``).join(', ')
const pct = (n, d) => `${Math.round((100 * n) / d)}%`

export function buildRegister(devices, groupsFile, handwritten) {
  const total = devices.length
  const byId = new Map(devices.map((d) => [d.id, d]))
  const groups = groupsFile.groups
  const examined = new Set(groups.flatMap((g) => g.ids))
  for (const id of examined) if (!byId.has(id)) throw new Error(`audit-groups.json names a device that is not in the catalog: ${id}`)

  const withRecord = devices.filter((d) => d.verification)
  const status = (s) => devices.filter((d) => d.verification?.status === s)
  const verified = status('verified')
  const inferred = status('inferred')
  const inQuestion = status('in_question')
  const checked = devices.filter((d) => d.verification && d.verification.status !== 'in_question')
  const examinedDevices = devices.filter((d) => examined.has(d.id))
  const examinedFlagged = examinedDevices.filter((d) => d.verification?.status === 'in_question')
  const examinedNoRecord = examinedDevices.filter((d) => !d.verification)
  const flaggedOnly = inQuestion.filter((d) => !examined.has(d.id))
  const noRecord = devices.filter((d) => !d.verification)
  const unexamined = total - examinedDevices.length

  const out = []
  const p = (...lines) => out.push(...lines)

  p('# Spec verification register', '')
  p('_Generated by `scripts/audit/gen-register.mjs` from the `verification` records in `src/data/devices.json`. Do not edit by hand: change the records or the inputs and regenerate. The prose sections are in `scripts/audit/register-handwritten.md`._', '')

  p('## Scope: read this first', '')
  p(`**Only ${examinedDevices.length} of ${total} devices in the catalog have been examined by any audit. The other ${unexamined} are unexamined.**`, '')
  p(`- **${checked.length}** have a \`verified\` (${verified.length}) or \`inferred\` (${inferred.length}) record: something about them was checked against a source.`)
  p(`- **${examinedFlagged.length}** more were examined but a value could not be confirmed, so they carry an \`in_question\` record instead.`)
  if (examinedNoRecord.length) p(`- ${examinedNoRecord.length} were examined and have no record (${code(examinedNoRecord.map((d) => d.id))}).`)
  p(`- **${flaggedOnly.length}** carry an \`in_question\` record without having been examined. These mark a field that nobody can verify against a source (a microphone's \`minPreampGain\` is an estimate; a DAW has no connectors). They are not evidence that the device was checked.`)
  p(`- **${noRecord.length}** have no record at all.`)
  p('')
  p(`In total ${withRecord.length} of ${total} devices have a record of some kind, but that figure counts the ${flaggedOnly.length} flag-only records and must not be read as "${pct(withRecord.length, total)} of the catalog has been checked". The honest figure is ${examinedDevices.length} of ${total} (${pct(examinedDevices.length, total)}), and for ${checked.length} of those (${pct(checked.length, total)} of the catalog) at least part of the spec rests on a source (${verified.length} confirmed, ${inferred.length} inferred).`)
  p('')
  p('**The 2026-10-06 stratified random sample found real errors outside everything that had been looked at before it** (8 of its 30 devices had a wrong field that changes a compatibility verdict). The devices that have not been examined should be assumed to contain errors of the same kind. **The original 8 devices of the first verification pass are not covered here:** their list was lost.', '')

  p('## Records by status', '')
  p('| Status | Devices | Meaning |', '|---|---|---|')
  p(`| \`verified\` | ${verified.length} | the listed fields were read from a manufacturer page or document, or two independent retailer pages |`)
  p(`| \`inferred\` | ${inferred.length} | the value was deduced from a related source (for example a sibling model); the record says what from |`)
  p(`| \`in_question\` | ${inQuestion.length} | a value could not be confirmed, or a source disagrees; the value is kept and flagged, and the record says why |`)
  p(`| no record | ${noRecord.length} | not examined |`)
  p('')
  p('A device has one record. When a device has mixed outcomes the status is the least certain one (`in_question`, then `inferred`, then `verified`), and what else was confirmed is written into the note. `fields` names the specs a record is about; an `in_question` record with `fields` leaves the device\'s other specs unflagged. The compatibility engine reads only `in_question` records, and only for phantom power: a phantom-power spec that is in question produces an explicit "unconfirmed" warning instead of a pass or a critical.', '')

  p('## What each audit examined', '')
  p('| Audit | Devices | With a verified or inferred record | Flagged `in_question` |', '|---|---|---|---|')
  for (const g of groups) {
    const ds = g.ids.map((id) => byId.get(id))
    const ok = ds.filter((d) => d.verification && d.verification.status !== 'in_question').length
    const q = ds.filter((d) => d.verification?.status === 'in_question').length
    const title = g.doc ? `${g.title} ([notes](${g.doc}))` : g.title
    const removed = g.removed?.length ? ` Removed because the product does not exist: ${code(g.removed)}.` : ''
    p(`| ${cell(title)}${removed} | ${ds.length} | ${ok} | ${q} |`)
  }
  p(`| **Distinct devices** (some were examined twice) | **${examinedDevices.length}** | **${examinedDevices.filter((d) => d.verification && d.verification.status !== 'in_question').length}** | **${examinedFlagged.length}** |`)
  p('')

  const row = (d) => {
    const v = d.verification
    return `| \`${d.id}\` | ${cell((v.fields ?? ['(whole device)']).join(', '))} | ${cell(v.source)} | ${v.checkedOn} | ${cell(v.note ?? '')} |`
  }
  const head = ['| Device | Fields | Source | Checked | Note |', '|---|---|---|---|---|']

  p(`## Verified (${verified.length})`, '')
  p(...head)
  for (const d of verified) p(row(d))
  p('')

  p(`## Inferred (${inferred.length})`, '')
  p(...head)
  for (const d of inferred) p(row(d))
  p('')

  p(`## In question, on devices that were examined (${examinedFlagged.length})`, '')
  p(...head)
  for (const d of examinedFlagged) p(row(d))
  p('')

  p(`## In question, on devices that were not examined (${flaggedOnly.length})`, '')
  p('These flag a field that cannot be checked against a published source. They say nothing about the rest of the device.', '')
  const bySig = new Map()
  for (const d of flaggedOnly) {
    const k = `${d.category}: ${(d.verification.fields ?? ['(whole device)']).join(', ')}`
    bySig.set(k, [...(bySig.get(k) ?? []), d])
  }
  p('| Category and field | Devices | Reason recorded |', '|---|---|---|')
  for (const [k, ds] of [...bySig].sort((a, b) => b[1].length - a[1].length)) {
    p(`| ${cell(k)} | ${ds.length} | ${cell(ds[0].verification.note)} |`)
  }
  p('')

  p(handwritten.trimEnd(), '')
  return out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n'
}

export function register() {
  const devices = JSON.parse(read('src/data/devices.json'))
  const groups = JSON.parse(read('scripts/audit/audit-groups.json'))
  return buildRegister(devices, groups, read('scripts/audit/register-handwritten.md'))
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  fs.writeFileSync(new URL('docs/spec-verification.md', ROOT), register())
  console.log('wrote docs/spec-verification.md')
}
